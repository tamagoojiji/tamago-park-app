function parseSaleRange(range: string): { saleStart?: string; saleEnd?: string } {
  if (!range) return {};
  const m = range.match(/(\d{4})年(\d{1,2})月(\d{1,2})日（[^）]+）～(?:(\d{4})年)?(\d{1,2})月(\d{1,2})日/);
  if (!m) return {};
  const [, y1, m1, d1, y2opt, m2, d2] = m;
  const pad = (s: string) => s.padStart(2, '0');
  return {
    saleStart: `${y1}-${pad(m1)}-${pad(d1)}`,
    saleEnd: `${y2opt || y1}-${pad(m2)}-${pad(d2)}`,
  };
}

